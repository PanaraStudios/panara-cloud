import { apiName, denyReason, type FunctionKind } from "./apiPolicy";
import type { Catalog, CatalogFunction, ValidatorJson } from "./apiSpec";

// Turns the registered Convex functions into the checked-in catalog
// (api/catalog.json) and the gateway's function list (apiFunctions.ts).
// scripts/generate-api.ts writes both; apiCatalog.test.ts fails when either
// no longer matches the code.

export type SourceModule = {
	// Path under convex/ without the extension, e.g. "applications/deploy".
	path: string;
	exports: Record<string, unknown>;
	source: string;
};

type Registered = {
	isPublic?: boolean;
	isQuery?: boolean;
	isMutation?: boolean;
	isAction?: boolean;
	exportArgs: () => string;
	exportReturns: () => string;
};

const kindOf = (fn: Registered): FunctionKind =>
	fn.isQuery ? "query" : fn.isMutation ? "mutation" : "action";

// The `//` lines directly above `export const <name> =`.
const docComment = (source: string, name: string): string | undefined => {
	const lines = source.split("\n");
	const at = lines.findIndex((line) =>
		line.startsWith(`export const ${name} =`),
	);
	const comment: string[] = [];
	for (let i = at - 1; i >= 0 && lines[i].startsWith("//"); i--) {
		comment.unshift(lines[i].replace(/^\/\/\s?/, ""));
	}
	const text = comment.join(" ").replace(/\s+/g, " ").trim();
	return text || undefined;
};

export type PublicFunction = CatalogFunction & { denied: string | null };

export const publicFunctions = (modules: SourceModule[]): PublicFunction[] =>
	modules
		.flatMap((module) =>
			Object.entries(module.exports).flatMap(([exportName, value]) => {
				const fn = value as Registered;
				if (typeof value !== "function" || fn.isPublic !== true) return [];
				const name = apiName(`${module.path}:${exportName}`);
				const description = docComment(module.source, exportName);
				const returns = JSON.parse(fn.exportReturns()) as ValidatorJson | null;
				return [
					{
						name,
						kind: kindOf(fn),
						...(description ? { description } : {}),
						args: JSON.parse(fn.exportArgs()) as ValidatorJson,
						returns,
						denied: denyReason(name),
					},
				];
			}),
		)
		.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

export const buildCatalog = (functions: PublicFunction[]): Catalog => ({
	functions: functions
		.filter((fn) => fn.denied === null)
		.map(({ denied: _denied, ...fn }) => fn),
});

export const renderFunctionList = (functions: PublicFunction[]): string =>
	[
		"// Generated by scripts/generate-api.ts from the public Convex functions.",
		"// Do not edit: run `pnpm --filter @panara-cloud/backend generate:api`.",
		'import type { FunctionKind } from "./apiPolicy";',
		"",
		"export const API_FUNCTIONS: Record<string, FunctionKind> = {",
		...functions.map((fn) => `\t"${fn.name}": "${fn.kind}",`),
		"};",
		"",
	].join("\n");

export const renderCatalog = (functions: PublicFunction[]): string =>
	`${JSON.stringify(buildCatalog(functions), null, "\t")}\n`;
